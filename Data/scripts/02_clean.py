"""Step 2: clean the raw Wide World Importers tables into tidy, typed, validated CSVs.

Input:  Data/raw/csv/*.csv (written by 01_extract_raw.py)
Output: Data/cleaned/*.csv and Data/reports/cleaning_report.md

Cleaning only reshapes what the source says; no value is invented or altered here. It
  - keeps the tables and columns that matter to Sales, Inventory, Procurement, Suppliers and Products,
  - drops audit columns, binary/JSON blobs, bank details and columns that are empty or constant,
  - replaces lookup ids (category, city, package type, contact person, ...) with their names,
  - trims and collapses whitespace in text, turns t/f into booleans, parses dates and integers,
  - checks keys, foreign keys, value ranges and date order, and fails if a check that should hold does not.
Known problems in the source that cleaning cannot fix are measured and written to the report.
"""
import json
from pathlib import Path

import pandas as pd

DATA_DIR = Path(__file__).resolve().parents[1]
RAW_DIR = DATA_DIR / "raw" / "csv"
OUT_DIR = DATA_DIR / "cleaned"
REPORT = DATA_DIR / "reports" / "cleaning_report.md"

report: list[str] = []
checks: list[tuple[str, bool, str]] = []


def raw(name: str) -> pd.DataFrame:
    return pd.read_csv(RAW_DIR / f"{name}.csv", low_memory=False)


def note(text: str = "") -> None:
    report.append(text)


def check(name: str, passed: bool, detail: str = "") -> None:
    checks.append((name, bool(passed), detail))


def clean_text(series: pd.Series) -> pd.Series:
    """Strip, collapse runs of whitespace, and turn empty strings into missing values."""
    cleaned = series.astype("string").str.replace(r"\s+", " ", regex=True).str.strip()
    return cleaned.mask(cleaned == "")


def to_bool(series: pd.Series) -> pd.Series:
    return series.map({"t": True, "f": False}).astype("boolean")


def to_date(series: pd.Series) -> pd.Series:
    return pd.to_datetime(series, format="%Y-%m-%d", errors="raise").dt.date


def to_int(series: pd.Series) -> pd.Series:
    return series.astype("Int64")


def fk_ok(child: pd.Series, parent: pd.Series) -> bool:
    return bool(child.dropna().isin(parent).all())


def save(name: str, frame: pd.DataFrame, key: str | list[str]) -> None:
    keys = [key] if isinstance(key, str) else key
    check(f"{name}: primary key {keys} is unique and not null",
          not frame.duplicated(keys).any() and not frame[keys].isna().any().any())
    check(f"{name}: no fully duplicated rows", not frame.duplicated().any())
    frame.to_csv(OUT_DIR / f"{name}.csv", index=False, date_format="%Y-%m-%d %H:%M:%S")
    missing = frame.isna().sum()
    missing = ", ".join(f"{column} {count:,}" for column, count in missing[missing > 0].items()) or "none"
    note(f"| `{name}.csv` | {len(frame):,} | {frame.shape[1]} | {missing} |")


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    REPORT.parent.mkdir(parents=True, exist_ok=True)

    # ---- lookups -------------------------------------------------------------------------
    people = raw("application.people").set_index("person_id")
    cities = raw("application.cities").merge(raw("application.state_provinces"), on="state_province_id").merge(
        raw("application.countries")[["country_id", "country_name"]], on="country_id")
    cities = cities.set_index("city_id")[["city_name", "state_province_name", "sales_territory", "country_name"]]
    cities.columns = ["city", "state_province", "sales_territory", "country"]
    delivery_methods = raw("application.delivery_methods").set_index("delivery_method_id")["delivery_method_name"]
    package_types = raw("warehouse.package_types").set_index("package_type_id")["package_type_name"]
    colors = raw("warehouse.colors").set_index("color_id")["color_name"]
    transaction_types = raw("application.transaction_types").set_index("transaction_type_id")["transaction_type_name"]

    note("# Cleaning report")
    note()
    note("Generated by `scripts/02_clean.py`. Source: Wide World Importers (Microsoft sample ERP database).")
    note()
    note("## Cleaned tables")
    note()
    note("| File | Rows | Columns | Missing values (column and count) |")
    note("|---|---:|---:|---|")

    # ---- suppliers -----------------------------------------------------------------------
    source = raw("purchasing.suppliers")
    categories = raw("purchasing.supplier_categories").set_index("supplier_category_id")["supplier_category_name"]
    suppliers = pd.DataFrame({
        "supplier_id": to_int(source.supplier_id),
        "supplier_name": clean_text(source.supplier_name),
        "supplier_category": source.supplier_category_id.map(categories),
        "contact_name": clean_text(source.primary_contact_person_id.map(people.full_name)),
        "contact_email": clean_text(source.primary_contact_person_id.map(people.email_address)).str.lower(),
        "phone": clean_text(source.phone_number),
        "website": clean_text(source.website_url).str.lower(),
        "delivery_method": source.delivery_method_id.map(delivery_methods),
        "city": source.delivery_city_id.map(cities.city),
        "state_province": source.delivery_city_id.map(cities.state_province),
        "country": source.delivery_city_id.map(cities.country),
        "postal_code": source.delivery_postal_code.astype("string").str.zfill(5),
        "payment_days": to_int(source.payment_days),
    })
    save("suppliers", suppliers, "supplier_id")

    # ---- products ------------------------------------------------------------------------
    source = raw("warehouse.stock_items")
    groups = raw("warehouse.stock_item_stock_groups").merge(raw("warehouse.stock_groups"), on="stock_group_id")
    product_categories = pd.DataFrame({
        "product_id": to_int(groups.stock_item_id),
        "category": clean_text(groups.stock_group_name),
    }).sort_values(["product_id", "category"]).reset_index(drop=True)
    # A product can sit in up to three groups. Its primary category is the most specific one,
    # i.e. the group with the fewest products (ties broken alphabetically).
    group_size = product_categories.groupby("category").size().rename("group_size")
    ranked = product_categories.join(group_size, on="category").sort_values(["product_id", "group_size", "category"])
    primary = ranked.groupby("product_id").category.first()
    all_categories = product_categories.groupby("product_id").category.agg("|".join)
    products = pd.DataFrame({
        "product_id": to_int(source.stock_item_id),
        "product_name": clean_text(source.stock_item_name),
        "supplier_id": to_int(source.supplier_id),
        "primary_category": source.stock_item_id.map(primary),
        "categories": source.stock_item_id.map(all_categories),
        "brand": clean_text(source.brand),
        "size": clean_text(source["size"]),
        "color": source.color_id.map(colors),
        "unit_package": source.unit_package_id.map(package_types),
        "outer_package": source.outer_package_id.map(package_types),
        "quantity_per_outer": to_int(source.quantity_per_outer),
        "lead_time_days": to_int(source.lead_time_days),
        "unit_price": source.unit_price.round(2),
        "recommended_retail_price": source.recommended_retail_price.round(2),
        "tax_rate": source.tax_rate,
        "typical_weight_per_unit_kg": source.typical_weight_per_unit,
        "is_chiller_stock": to_bool(source.is_chiller_stock),
        "tags": source.tags.map(lambda value: "|".join(json.loads(value))).astype("string").mask(lambda s: s == ""),
    })
    check("products: every product has a supplier that exists", fk_ok(products.supplier_id, suppliers.supplier_id))
    check("products: every product has at least one category", products.primary_category.notna().all())
    check("products: unit_price > 0 and recommended_retail_price >= unit_price",
          (products.unit_price > 0).all() and (products.recommended_retail_price >= products.unit_price).all())
    check("products: quantity_per_outer >= 1 and lead_time_days >= 1",
          (products.quantity_per_outer >= 1).all() and (products.lead_time_days >= 1).all())
    save("products", products, "product_id")
    save("product_categories", product_categories, ["product_id", "category"])

    # ---- customers -----------------------------------------------------------------------
    source = raw("sales.customers")
    categories = raw("sales.customer_categories").set_index("customer_category_id")["customer_category_name"]
    buying_groups = raw("sales.buying_groups").set_index("buying_group_id")["buying_group_name"]
    customers = pd.DataFrame({
        "customer_id": to_int(source.customer_id),
        "customer_name": clean_text(source.customer_name),
        "customer_category": source.customer_category_id.map(categories),
        "buying_group": source.buying_group_id.map(buying_groups),
        "bill_to_customer_id": to_int(source.bill_to_customer_id),
        "city": source.delivery_city_id.map(cities.city),
        "state_province": source.delivery_city_id.map(cities.state_province),
        "sales_territory": source.delivery_city_id.map(cities.sales_territory),
        "country": source.delivery_city_id.map(cities.country),
        "postal_code": source.delivery_postal_code.astype("string").str.zfill(5),
        "delivery_method": source.delivery_method_id.map(delivery_methods),
        "credit_limit": source.credit_limit,
        "account_opened_date": to_date(source.account_opened_date),
        "standard_discount_percentage": source.standard_discount_percentage,
        "payment_days": to_int(source.payment_days),
        "is_on_credit_hold": to_bool(source.is_on_credit_hold),
        "phone": clean_text(source.phone_number),
        "website": clean_text(source.website_url).str.lower(),
    })
    check("customers: bill_to_customer_id exists", fk_ok(customers.bill_to_customer_id, customers.customer_id))
    save("customers", customers, "customer_id")

    # ---- inventory -----------------------------------------------------------------------
    source = raw("warehouse.stock_item_holdings")
    inventory = pd.DataFrame({
        "product_id": to_int(source.stock_item_id),
        "bin_location": clean_text(source.bin_location),
        "quantity_on_hand": to_int(source.quantity_on_hand),
        "last_stocktake_quantity": to_int(source.last_stocktake_quantity),
        "last_cost_price": source.last_cost_price.round(2),
        "reorder_level": to_int(source.reorder_level),
        "target_stock_level": to_int(source.target_stock_level),
        "last_updated": pd.to_datetime(source.last_edited_when),
    })
    check("inventory: one row per product, product exists",
          fk_ok(inventory.product_id, products.product_id) and len(inventory) == len(products))
    check("inventory: quantity_on_hand >= 0, reorder_level > 0, target_stock_level >= reorder_level",
          (inventory.quantity_on_hand >= 0).all() and (inventory.reorder_level > 0).all()
          and (inventory.target_stock_level >= inventory.reorder_level).all())
    save("inventory", inventory, "product_id")

    # ---- sales orders --------------------------------------------------------------------
    source = raw("sales.orders")
    invoices = raw("sales.invoices")
    check("invoices: at most one invoice per order, none is a credit note",
          not invoices.order_id.duplicated().any() and (invoices.is_credit_note == "f").all())
    invoices = invoices.set_index("order_id")
    delivered_at = pd.to_datetime(source.order_id.map(invoices.confirmed_delivery_time))
    invoice_date = pd.to_datetime(source.order_id.map(invoices.invoice_date))
    sales_orders = pd.DataFrame({
        "order_id": to_int(source.order_id),
        "customer_id": to_int(source.customer_id),
        "salesperson": clean_text(source.salesperson_person_id.map(people.full_name)),
        "order_date": to_date(source.order_date),
        "expected_delivery_date": to_date(source.expected_delivery_date),
        "picking_completed_at": pd.to_datetime(source.picking_completed_when),
        "invoice_id": to_int(source.order_id.map(invoices.invoice_id)),
        "invoice_date": invoice_date.dt.date,
        "delivered_at": delivered_at,
        "backorder_order_id": to_int(source.backorder_order_id),
        "customer_purchase_order_number": source.customer_purchase_order_number.astype("string"),
        # Stated by the source: delivered = delivery confirmed, invoiced = invoiced but no
        # delivery confirmation yet, open = never picked or invoiced.
        "fulfilment_status": "open",
    })
    sales_orders.loc[invoice_date.notna(), "fulfilment_status"] = "invoiced"
    sales_orders.loc[delivered_at.notna(), "fulfilment_status"] = "delivered"
    check("sales_orders: customer exists", fk_ok(sales_orders.customer_id, customers.customer_id))
    check("sales_orders: backorder_order_id exists", fk_ok(sales_orders.backorder_order_id, sales_orders.order_id))
    check("sales_orders: expected_delivery_date is after order_date",
          (sales_orders.expected_delivery_date > sales_orders.order_date).all())
    check("sales_orders: invoice_date is on or after order_date",
          (invoice_date.dropna().dt.date >= sales_orders.order_date[invoice_date.notna()]).all())
    save("sales_orders", sales_orders, "order_id")

    source = raw("sales.order_lines")
    sales_order_lines = pd.DataFrame({
        "order_line_id": to_int(source.order_line_id),
        "order_id": to_int(source.order_id),
        "product_id": to_int(source.stock_item_id),
        "quantity": to_int(source.quantity),
        "picked_quantity": to_int(source.picked_quantity),
        "unit_price": source.unit_price.round(2),
        "tax_rate": source.tax_rate,
        "line_total_excl_tax": (source.quantity * source.unit_price).round(2),
        "picking_completed_at": pd.to_datetime(source.picking_completed_when),
    }).sort_values("order_line_id").reset_index(drop=True)
    check("sales_order_lines: order and product exist",
          fk_ok(sales_order_lines.order_id, sales_orders.order_id)
          and fk_ok(sales_order_lines.product_id, products.product_id))
    check("sales_order_lines: every order has at least one line",
          sales_orders.order_id.isin(sales_order_lines.order_id).all())
    check("sales_order_lines: quantity > 0, unit_price > 0, picked_quantity is 0 or the full quantity",
          (sales_order_lines.quantity > 0).all() and (sales_order_lines.unit_price > 0).all()
          and ((sales_order_lines.picked_quantity == 0)
               | (sales_order_lines.picked_quantity == sales_order_lines.quantity)).all())
    list_price = sales_order_lines.product_id.map(products.set_index("product_id").unit_price)
    check("sales_order_lines: unit_price never exceeds the product's list price",
          (sales_order_lines.unit_price <= list_price).all())
    save("sales_order_lines", sales_order_lines, "order_line_id")

    # ---- purchase orders -----------------------------------------------------------------
    source = raw("purchasing.purchase_orders")
    purchase_orders = pd.DataFrame({
        "purchase_order_id": to_int(source.purchase_order_id),
        "supplier_id": to_int(source.supplier_id),
        "order_date": to_date(source.order_date),
        "expected_delivery_date": to_date(source.expected_delivery_date),
        "delivery_method": source.delivery_method_id.map(delivery_methods),
        "ordered_by": clean_text(source.contact_person_id.map(people.full_name)),
        "supplier_reference": clean_text(source.supplier_reference),
        "is_finalized": to_bool(source.is_order_finalized),
    })
    check("purchase_orders: supplier exists", fk_ok(purchase_orders.supplier_id, suppliers.supplier_id))
    check("purchase_orders: expected_delivery_date is after order_date",
          (purchase_orders.expected_delivery_date > purchase_orders.order_date).all())
    save("purchase_orders", purchase_orders, "purchase_order_id")

    source = raw("purchasing.purchase_order_lines")
    per_outer = source.stock_item_id.map(products.set_index("product_id").quantity_per_outer).astype("int64")
    purchase_order_lines = pd.DataFrame({
        "purchase_order_line_id": to_int(source.purchase_order_line_id),
        "purchase_order_id": to_int(source.purchase_order_id),
        "product_id": to_int(source.stock_item_id),
        "package_type": source.package_type_id.map(package_types),
        "quantity_per_outer": per_outer,
        "ordered_outers": to_int(source.ordered_outers),
        "received_outers": to_int(source.received_outers),
        "ordered_units": to_int(source.ordered_outers * per_outer),
        "received_units": to_int(source.received_outers * per_outer),
        "expected_price_per_outer": source.expected_unit_price_per_outer.round(2),
        "expected_cost_per_unit": (source.expected_unit_price_per_outer / per_outer).round(4),
        "last_receipt_date": pd.to_datetime(source.last_receipt_date).dt.date,
        "is_finalized": to_bool(source.is_order_line_finalized),
    })
    lines = purchase_order_lines.merge(purchase_orders, on="purchase_order_id", suffixes=("", "_order"))
    check("purchase_order_lines: purchase order and product exist",
          fk_ok(purchase_order_lines.purchase_order_id, purchase_orders.purchase_order_id)
          and fk_ok(purchase_order_lines.product_id, products.product_id))
    check("purchase_order_lines: every purchase order has at least one line",
          purchase_orders.purchase_order_id.isin(purchase_order_lines.purchase_order_id).all())
    check("purchase_order_lines: the order's supplier is the product's supplier",
          (lines.supplier_id == lines.product_id.map(products.set_index("product_id").supplier_id)).all())
    check("purchase_order_lines: ordered_outers > 0, 0 <= received_outers <= ordered_outers, price > 0",
          (purchase_order_lines.ordered_outers > 0).all() and (purchase_order_lines.expected_price_per_outer > 0).all()
          and purchase_order_lines.received_outers.between(0, purchase_order_lines.ordered_outers).all())
    received = lines.last_receipt_date.notna()
    check("purchase_order_lines: last_receipt_date is on or after the order date",
          (lines.last_receipt_date[received] >= lines.order_date[received]).all())
    check("purchase_order_lines: a line has a receipt date exactly when it is finalized",
          (received == lines.is_finalized).all())
    save("purchase_order_lines", purchase_order_lines, "purchase_order_line_id")

    # ---- stock movements -----------------------------------------------------------------
    source = raw("warehouse.stock_item_transactions")
    stock_movements = pd.DataFrame({
        "stock_movement_id": to_int(source.stock_item_transaction_id),
        "product_id": to_int(source.stock_item_id),
        "movement_type": source.transaction_type_id.map(transaction_types),
        "quantity": to_int(source.quantity),
        "occurred_at": pd.to_datetime(source.transaction_occurred_when),
        "customer_id": to_int(source.customer_id),
        "invoice_id": to_int(source.invoice_id),
        "supplier_id": to_int(source.supplier_id),
        "purchase_order_id": to_int(source.purchase_order_id),
    }).sort_values("stock_movement_id").reset_index(drop=True)
    issue, receipt = stock_movements.movement_type == "Stock Issue", stock_movements.movement_type == "Stock Receipt"
    check("stock_movements: product, customer, supplier and purchase order exist",
          fk_ok(stock_movements.product_id, products.product_id)
          and fk_ok(stock_movements.customer_id, customers.customer_id)
          and fk_ok(stock_movements.supplier_id, suppliers.supplier_id)
          and fk_ok(stock_movements.purchase_order_id, purchase_orders.purchase_order_id))
    check("stock_movements: issues are negative and reference an invoice, receipts are positive and reference a PO",
          (stock_movements.quantity[issue] < 0).all() and stock_movements.invoice_id[issue].notna().all()
          and (stock_movements.quantity[receipt] > 0).all() and stock_movements.purchase_order_id[receipt].notna().all())
    save("stock_movements", stock_movements, "stock_movement_id")

    # ---- report --------------------------------------------------------------------------
    start, end = sales_orders.order_date.min(), sales_orders.order_date.max()
    note()
    note(f"Period covered: {start} to {end}. All monetary values are in the source's single currency (USD).")
    note()
    note("## What was changed")
    note()
    note("- Kept 10 of the 29 source tables' worth of content; lookup tables were folded in as names.")
    note("- Dropped: `last_edited_by` / `last_edited_when` audit columns, `photo`, `custom_fields`, "
         "`search_details`, `returned_delivery_data`, bank account details, fax numbers, postal (PO box) "
         "addresses, and columns that are entirely empty in the source (`comments`, `internal_comments`, "
         "`delivery_instructions`, `delivery_run`, `run_position`, `credit_note_reason`).")
    note("- Dropped `is_undersupply_backordered` (the same value on all 73,595 orders).")
    trimmed = int((raw("warehouse.stock_items").stock_item_name != products.product_name).sum()
                  + (raw("sales.customers").customer_name != customers.customer_name).sum())
    note(f"- Whitespace normalised in names ({trimmed} product and customer names had double or trailing spaces).")
    note("- `t`/`f` flags became `True`/`False`; dates are ISO `YYYY-MM-DD`; identifiers and quantities are integers.")
    note("- Added, computed directly from source columns: `line_total_excl_tax` (quantity x unit_price), "
         "`ordered_units` / `received_units` (outers x quantity_per_outer), `expected_cost_per_unit` "
         "(price per outer / quantity_per_outer), `primary_category`, `fulfilment_status`.")
    note("- No rows were removed: there were no duplicate rows, duplicate keys or orphaned references.")
    note()
    note("## Validation checks")
    note()
    note("| Check | Result |")
    note("|---|---|")
    for name, passed, detail in checks:
        note(f"| {name} | {'pass' if passed else 'FAIL'}{' - ' + detail if detail else ''} |")

    # Problems that are in the source itself. They are reported, not repaired.
    movement = stock_movements.sort_values(["product_id", "occurred_at", "stock_movement_id"])
    running = movement.groupby("product_id").quantity.cumsum()
    net = stock_movements.groupby("product_id").quantity.sum()
    on_hand = inventory.set_index("product_id").quantity_on_hand
    issued = -stock_movements[issue].groupby("product_id").quantity.sum()
    received_units = stock_movements[receipt].groupby("product_id").quantity.sum().reindex(issued.index, fill_value=0)
    days = (pd.Timestamp(end) - pd.Timestamp(start)).days + 1
    cover = on_hand / (issued / days)
    lead = (pd.to_datetime(lines.last_receipt_date) - pd.to_datetime(lines.order_date)).dt.days
    late = pd.to_datetime(lines.last_receipt_date) > pd.to_datetime(lines.expected_delivery_date)
    orders_per_supplier = purchase_orders.groupby("supplier_id").size()
    products_per_supplier = products.groupby("supplier_id").size()
    open_orders = sales_orders[sales_orders.fulfilment_status == "open"]
    note()
    note("## Problems in the source data (reported, not repaired)")
    note()
    note("These come from the way the sample database was generated. They affect the inventory and "
         "procurement side; the sales side is consistent.")
    note()
    note(f"1. **Stock on hand does not follow from the stock movements.** `quantity_on_hand` equals the sum of "
         f"movements for {int((on_hand == net).sum())} of {len(on_hand)} products, and the running balance of "
         f"movements goes negative at some point for {int((running.groupby(movement.product_id).min() < 0).sum())} "
         f"products.")
    note(f"2. **Stock levels are far above demand.** Median stock on hand is {int(on_hand.median()):,} units against "
         f"a median demand of {issued.div(days).median():.1f} units a day, i.e. a median of "
         f"{cover.median() / 365:.0f} years of cover. Only {int((on_hand < inventory.set_index('product_id').reorder_level).sum())} "
         f"products are below their reorder level.")
    note(f"3. **Purchasing is concentrated on few products.** {int((received_units == 0).sum())} products have no "
         f"stock receipt at all and {int((received_units < issued).sum())} received fewer units than were sold, "
         f"while total receipts ({int(received_units.sum()):,} units) are {received_units.sum() / issued.sum():.1f} "
         f"times total sales ({int(issued.sum()):,} units).")
    note(f"4. **Deliveries are never late.** Every received purchase-order line arrived {int(lead.min())} to "
         f"{int(lead.max())} days after ordering (mean {lead.mean():.2f}); {int(late.sum())} lines arrived after "
         f"the expected date, which is usually 20 days out. Supplier delay analysis has nothing to find here.")
    note(f"5. **Few active suppliers.** {len(products_per_supplier)} of {len(suppliers)} suppliers supply any product, "
         f"and {int((orders_per_supplier >= 100).sum())} of them account for "
         f"{orders_per_supplier[orders_per_supplier >= 100].sum():,} of {len(purchase_orders):,} purchase orders.")
    note(f"6. **Old orders left open.** {len(open_orders):,} sales orders ({len(open_orders) / len(sales_orders):.1%}) "
         f"were never picked or invoiced, dating back to {open_orders.order_date.min()}.")
    cost_above = int((inventory.set_index("product_id").last_cost_price.sort_index()
                      >= products.set_index("product_id").unit_price.sort_index()).sum())
    note(f"7. **Cost at or above selling price** for {cost_above} products (`last_cost_price` >= `unit_price`).")

    REPORT.write_text("\n".join(report) + "\n", encoding="utf-8")
    failed = [name for name, passed, _ in checks if not passed]
    print(f"{len(checks) - len(failed)}/{len(checks)} checks passed; report: {REPORT.relative_to(DATA_DIR)}")
    for name in failed:
        print("FAILED:", name)
    raise SystemExit(1 if failed else 0)


